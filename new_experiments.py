# --------------------------------------------------------------------------- #
#  T2 — SDPI convergence comparison against the naive fixed-point solver
# --------------------------------------------------------------------------- #
def exp_sdpi():
    report = {}
    for name, spec in [("humanoid", models.humanoid_spec()),
                       ("microgrid", models.microgrid_spec())]:
        A, B, E = spec["A"], spec["B"], spec["E"]
        Q, R, alpha, lam = spec["Q"], spec["R"], spec["alpha"], spec["lam"]
        V = spec["d_bar"].reshape(1, -1)
        base = core.solve_drc_pi(A, B, E, Q, R, alpha, lam, spec["d_bar"])
        res = sdpi.solve_sdpi(A, B, E, Q, R, alpha, lam, V)

        diffs = {k: float(np.linalg.norm(res[k] - base[k]))
                 for k in ("K", "p", "N", "z", "P")}
        report[name] = dict(
            baseline=dict(iters=base["iters"], rho_G=base["rho_G"],
                          lam_min_P=base["lam_min_P"], p=base["p"]),
            sdpi=dict(phase1_steps=res["phase1_steps"],
                      switched_at=res["switched_at"],
                      phase2_steps=res["phase2_steps"],
                      rho_G=res["rho_G"],
                      initialization=res["initialization"]["source"],
                      stop_reason=res["stop_reason"],
                      final_delta=res["final_delta"],
                      monotonic_violations=res["monotonic_violations"]),
            diffs=diffs,
            history=[dict(step=h["step"], phase=h["phase"],
                          beta_scale=h["beta_scale"],
                          beta_interp=h["beta_interp"],
                          rho_G=h["rho_G"],
                          residual_max=h["residual_max"],
                          violations=h.get("violations"))
                     for h in res["history"]])
    return report


# --------------------------------------------------------------------------- #
#  T3 / T5 — Alg.4 closed-loop identification scan
# --------------------------------------------------------------------------- #
def exp_alg4(Ns=(500, 1000, 2000, 5000), seeds=range(8), expl_scale=1.0,
             dist_mode="adversarial"):
    """Run the canonical one-step Algorithm-4 rate scan.

    The former reduced closed-loop/no-adversary LQR route is retained only in
    the historical helper functions above; it is no longer the reported
    Algorithm-4 experiment.  ``dist_mode`` is accepted for backward
    compatibility because the identification design always uses the measured
    affine disturbance and a designed probe in the canonical runner.
    """
    import algorithm4
    report = {}
    for name, spec in [("humanoid", models.humanoid_spec()),
                       ("microgrid", models.microgrid_spec())]:
        report[name] = {
            "ols": algorithm4.alg4_slope_scan(
                spec, Ns=Ns, seeds=seeds, use_iv=False, rounds=1,
                expl_scale=expl_scale, dist_probe_scale=0.5),
            "iv": algorithm4.alg4_slope_scan(
                spec, Ns=Ns, seeds=seeds, use_iv=True, rounds=1,
                expl_scale=expl_scale, dist_probe_scale=0.5),
        }
    report["scope"] = ("one fixed-policy evaluation/improvement round; "
                       "no global outer-loop rate is claimed")
    report["dist_mode_input"] = dist_mode
    return report


# --------------------------------------------------------------------------- #
#  T4 — Thm.3 X-criterion feasibility check
# --------------------------------------------------------------------------- #
def exp_thm3():
    report = {}
    for name, spec in [("humanoid", models.humanoid_spec()),
                       ("microgrid", models.microgrid_spec())]:
        A, B, E = spec["A"], spec["B"], spec["E"]
        Q, R, alpha, lam = spec["Q"], spec["R"], spec["alpha"], spec["lam"]
        opt = core.solve_drc_pi(A, B, E, Q, R, alpha, lam, spec["d_bar"])
        PhiP = Q + opt["K"].T @ R @ opt["K"] - lam * (opt["N"].T @ opt["N"])
        rep = thm3.check_criterion(opt["G"], opt["P"], PhiP, alpha, name)
        G_bad, rho0 = thm3.destabilize(opt["G"], 1.02)
        rep_bad = thm3.check_criterion(G_bad, opt["P"], PhiP, alpha,
                                       name + "-destabilized")
        report[name] = dict(stable=rep, destabilized=rep_bad,
                            rho_G=rep["rho_G"])
    return report


# --------------------------------------------------------------------------- #
#  T5c — static truth-usage audit: where do A, B, E appear in the data-driven
#  module? They must occur only in data generation and in error metrics.
# --------------------------------------------------------------------------- #
def audit_truth_usage():
    here = os.path.dirname(os.path.abspath(__file__))
    path = os.path.join(here, "data_driven.py")
    src = open(path, encoding="utf-8").read()
    funcs = re.findall(r"^def (\w+)\(", src, flags=re.M)
    body = {f: src.split(f"def {f}(")[1].split("\ndef ")[0] for f in funcs}
    truth_refs = {}
    for f, txt in body.items():
        hits = [tok for tok in ("spec[\"A\"]", "spec['A']", "spec[\"B\"]",
                                "spec['B']", "spec[\"E\"]", "spec['E']")
                if tok in txt]
        if hits:
            truth_refs[f] = hits
    # ``collect_support_points`` is data generation; the two error functions
    # are scoring only.  Neither is on the controller-synthesis path.
    allowed = {"collect_closed_loop", "collect_support_points",
               "identification_errors", "full_identification_errors"}
    extra = {f: v for f, v in truth_refs.items() if f not in allowed}
    return dict(functions=funcs, truth_reference_locations=truth_refs,
                compliant=len(extra) == 0, unexpected=extra)
